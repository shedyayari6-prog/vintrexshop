const KEY = "vintrex_lang";

function detect() {
  try {
    const saved = localStorage.getItem(KEY);
    if (saved && DICT[saved]) return saved;
  } catch { /* storage unavailable */ }
  const nav = String((typeof navigator !== "undefined" && navigator.language) || "en")
    .slice(0, 2)
    .toLowerCase();
  return DICT[nav] ? nav : "en";
}

let current = detect();
const listeners = new Set();

export function setLang(lang) {
  if (!DICT[lang] || lang === current) return;
  current = lang;
  try { localStorage.setItem(KEY, lang); } catch { /* storage unavailable */ }
  listeners.forEach((fn) => fn());
}

const subscribe = (fn) => {
  listeners.add(fn);
  return () => listeners.delete(fn);
};

export function translate(lang, key, vars) {
  let text = DICT[lang]?.[key] ?? DICT.en[key] ?? key;
  if (vars) text = text.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ""));
  return text;
}

// const { t, lang, dir, setLang } = useLang();
export function useLang() {
  const lang = useSyncExternalStore(subscribe, () => current, () => "en");
  return {
    lang,
    dir: lang === "ar" ? "rtl" : "ltr",
    t: (key, vars) => translate(lang, key, vars),
    setLang,
  };
}
